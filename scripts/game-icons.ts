interface IconSet {
  icons: Record<string, { body: string }>
  aliases?: Record<string, { parent: string }>
}

const require = createRequire(import.meta.url)
const set = JSON.parse(
  readFileSync(require.resolve('@iconify-json/game-icons/icons.json'), 'utf8'),
) as IconSet

const body = (name: string): string => {
  const icon = set.icons[name] ?? set.icons[set.aliases?.[name]?.parent ?? '']
  if (!icon) throw new Error(`game-icons: unknown icon "${name}"`)
  // Some files carry a black background square: drop it, keep the glyph.
  return icon.body
    .replace(/<path d="M0 0h512v512H0z"\/>/g, '')
    .replace(/fill="#fff"/g, 'fill="currentColor"')
}

const entries = [...new Set(NAMES)]
  .sort()
  .map((name) => `  '${name}': ${JSON.stringify(body(name))},`)
const out = `// Generated by scripts/game-icons.ts from game-icons.net (CC BY 3.0). Do not edit.
export const GAME_ICON_BODIES = {
${entries.join('\n')}
} as const

export type GameIconName = keyof typeof GAME_ICON_BODIES
`
writeFileSync(resolve(import.meta.dirname, '../src/components/gameIcons.generated.ts'), out)
console.log(`${entries.length} game icons written.`)
